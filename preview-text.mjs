export function createPreviewText({SHULKER_BOXES,WOOL_COLORS,WOOL_FORMS,MATERIAL_FORMS,FINISHING_BLOCKS,WOOD_BLOCKS,FIXTURE_BLOCKS}) {
 return Object.fromEntries(['en','ru'].map(lang=>{
  const index=lang==='en'?1:2;
  const cards=rows=>Object.fromEntries(rows.map(row=>['card_'+row[0],row[index]]));
  const labels=rows=>Object.fromEntries(rows.map(row=>[row[0],row[index]]));
  return [lang,{
   ...cards(FIXTURE_BLOCKS),...cards(WOOD_BLOCKS),...cards(FINISHING_BLOCKS),
   ...Object.fromEntries(WOOL_COLORS.flatMap(row=>WOOL_FORMS.concat(MATERIAL_FORMS).map(([form,en,ru,gender])=>['card_'+row[0]+'_'+form,lang==='en'?row[1]+' '+en:row[gender]+' '+ru]))),
   ...labels(CARDS),
   ...Object.fromEntries(SHULKER_BOXES.map(row=>['card_'+row[0]+'_shulker_box',row[index]])),
   ...labels(CONTROLS)
  }];
 }));
}
